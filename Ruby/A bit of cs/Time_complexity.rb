# common Big 0 complexities

| Notation | Name | Example | Growth |
| --- | --- | --- | --- |
| O(1) | Constant | Array lookup ``arr[i]`` | Always 1 step |
| O(log N) | Logarithmic | Binary Search | Steps grow slowly |
| O(N) | Linear | Iterating over array | Steps = N |
| O(N log N) | Linearithmic | Merge Sort | Efficient sorting |
| O(N²) | Quadratic | Nested loops | Steps = N² |
| O(N³) | Cubic | Triple nested loops | Steps = N³ |
| O(2ⁿ) | Exponential | Recursive subset generation | Explodes fast |
| O(N!) | Factorial | Permutations | Grows impossibly fast |